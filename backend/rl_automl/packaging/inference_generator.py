@dataclass
class GeneratedInference:
    files: list[Path]
    example_input: pd.DataFrame | None = None
    requirements: list[str] | None = None


class InferenceGenerator:
    def __init__(self, config: AutoMLConfig | None = None) -> None:
        self.config = config or AutoMLConfig()

    def generate(
        self,
        package: ModelPackage,
        *,
        split_summary: dict[str, Any] | None = None,
        include_readme: bool | None = None,
    ) -> GeneratedInference:
        """Write every inference-side file into an already-exported package directory."""
        directory = package.directory
        inference_dir = directory / "inference"
        inference_dir.mkdir(parents=True, exist_ok=True)

        written: list[Path] = []

        loader = MODEL_LOADER_TEMPLATE.replace("$MODEL_FILENAME", "model.joblib").replace(
            "$RUNTIME_MODULES", json.dumps(runtime_module_map(), indent=4)
        )
        written.append(self._write(inference_dir / "model_loader.py", loader))
        written.append(self._write(inference_dir / "predict.py", PREDICT_TEMPLATE))

        example = self._example_frame(package.schema)
        if example is not None:
            example_path = inference_dir / "example_input.csv"
            example.to_csv(example_path, index=False)
            written.append(example_path)

        requirements = self._requirements(package)
        written.append(
            self._write(
                directory / "requirements.txt",
                REQUIREMENTS_TEMPLATE.replace(
                    "$REQUIREMENTS", "\n".join(requirements[:-1])
                ).replace("$FRAMEWORK_REQUIREMENT", requirements[-1]),
            )
        )

        should_write_readme = (
            self.config.packaging.include_readme if include_readme is None else include_readme
        )
        if should_write_readme:
            written.append(
                self._write(
                    directory / "README.md",
                    self._readme(package, example, split_summary or {}),
                )
            )

        return GeneratedInference(files=written, example_input=example, requirements=requirements)

    # -- pieces ------------------------------------------------------------------

    def _requirements(self, package: ModelPackage) -> list[str]:
        """Inference dependencies only. The training environment is not shipped."""
        base = list(self.config.packaging.inference_requirements)
        framework = str(package.metadata.get("framework", "scikit-learn"))
        framework_line = {
            "xgboost": "xgboost>=2.0",
            "lightgbm": "lightgbm>=4.0",
            "torch": "torch>=2.2",
        }.get(framework, "scikit-learn>=1.4")
        if framework == "scikit-learn" and any(line.startswith("scikit-learn") for line in base):
            return base
        return [*base, framework_line]

    def _example_frame(self, schema: FeatureSchema) -> pd.DataFrame | None:
        """A single schema-shaped row using safe placeholder values.

        Synthesised on purpose: shipping real rows would leak user data into a downloadable
        artifact.
        """
        if not schema.features:
            return None

        row: dict[str, Any] = {}
        for feature in schema.features:
            if feature.kind == "numeric":
                row[feature.name] = 0.0
            elif feature.kind == "datetime":
                row[feature.name] = "2024-01-01"
            elif feature.example_values:
                row[feature.name] = feature.example_values[0]
            else:
                row[feature.name] = "value"
        return pd.DataFrame([row])

    def _readme(
        self,
        package: ModelPackage,
        example: pd.DataFrame | None,
        split_summary: dict[str, Any],
    ) -> str:
        metadata = package.metadata
        schema = package.schema
        dataset = metadata.get("dataset", {})
        dataset_metadata = {}
        dataset_metadata_path = package.directory / "metadata" / "dataset_metadata.json"
        if dataset_metadata_path.is_file():
            import json

            dataset_metadata = json.loads(dataset_metadata_path.read_text(encoding="utf-8"))

        feature_rows = "\n".join(
            f"| `{feature.name}` | {feature.kind} | {'yes' if feature.required else 'no'} | "
            f"{'yes' if feature.nullable else 'no'} | {feature.n_unique or ''} |"
            for feature in schema.features
        )
        feature_table = (
            "| Column | Kind | Required | Nullable | Unique values |\n"
            "| --- | --- | --- | --- | --- |\n" + feature_rows
            if feature_rows
            else "_No input columns were recorded._"
        )

        metrics_block = self._metrics_block(metadata)
        example_input = example.to_csv(index=False).strip() if example is not None else "n/a"
        example_output = self._example_output(metadata, schema)

        preprocessing = metadata.get("preprocessing") or []
        preprocessing_list = (
            "\n".join(f"{index + 1}. `{name}`" for index, name in enumerate(preprocessing))
            if preprocessing
            else "_None beyond the schema coercion performed by the loader._"
        )

        warnings = list(metadata.get("warnings", [])) + list(dataset_metadata.get("warnings", []))
        warnings_block = (
            "## Recorded warnings\n\n" + "\n".join(f"* {warning}" for warning in warnings)
            if warnings
            else ""
        )

        contents = "\n".join(
            str(path.relative_to(package.directory)).replace("\\", "/") for path in package.files()
        )

        target_note = (
            f"`{schema.target}` is the training target and is **not** an input column."
            if schema.target
            else "This is an unsupervised model; no target column was used."
        )

        onnx_note = (
            "\n* An ONNX export is included at `model/model.onnx`; it was verified to match "
            "the native model on a probe sample.\n"
            if package.has_onnx()
            else ""
        )

        download_note = (
            "This package was verified after being archived: the ZIP was re-opened, its "
            "checksums tested, and its model reloaded and compared against the in-process "
            "model."
        )

        return Template(README_TEMPLATE).safe_substitute(
            MODEL_DISPLAY_NAME=metadata.get("model", "Unknown"),
            MODEL_KEY=metadata.get("model_key", ""),
            FRAMEWORK=metadata.get("framework", ""),
            TASK_TYPE=metadata.get("task", ""),
            OBJECTIVE=metadata.get("objective", ""),
            PRIMARY_METRIC=metadata.get("primary_metric", ""),
            METRIC_DIRECTION=metadata.get("metric_direction", ""),
            VALIDATION_SCORE=_format_number(metadata.get("validation_score")),
            TEST_SCORE=_format_number(metadata.get("test_score")),
            RAW_FEATURES=str(metadata.get("raw_features", "")),
            TRANSFORMED_FEATURES=str(metadata.get("features", "")),
            TRAINING_TIME=_format_number(metadata.get("resource_usage", {}).get("training_time_s")),
            PEAK_MEMORY=_format_number(metadata.get("resource_usage", {}).get("peak_memory_mb")),
            TRAINING_TIMESTAMP=metadata.get("training_timestamp", ""),
            RUN_ID=metadata.get("run_id", ""),
            DOWNLOAD_NOTE=download_note,
            FEATURE_TABLE=feature_table,
            TARGET_NOTE=target_note,
            EXAMPLE_INPUT=example_input,
            EXAMPLE_OUTPUT=example_output,
            PREPROCESSING_LIST=preprocessing_list,
            METRICS_BLOCK=metrics_block,
            DATASET_NAME=dataset.get("name", ""),
            DATASET_SHA=dataset.get("sha256", ""),
            DATASET_ROWS=str(dataset_metadata.get("n_rows", "")),
            DATASET_COLS=str(dataset_metadata.get("n_cols", "")),
            DATASET_MISSING=_format_number(dataset_metadata.get("missing_ratio")),
            SPLIT_DESCRIPTION=_split_description(split_summary),
            WARNINGS_BLOCK=warnings_block,
            CONTENTS=contents,
            ONNX_NOTE=onnx_note,
        )

    @staticmethod
    def _metrics_block(metadata: dict[str, Any]) -> str:
        validation = metadata.get("validation_metrics") or {}
        test = metadata.get("test_metrics") or {}
        names = sorted(set(validation) | set(test))
        if not names:
            return "_No metrics were recorded._"
        rows = "\n".join(
            f"| {name} | {_format_number(validation.get(name))} "
            f"| {_format_number(test.get(name))} |"
            for name in names
        )
        return "| Metric | Validation | Test |\n| --- | --- | --- |\n" + rows

    @staticmethod
    def _example_output(metadata: dict[str, Any], schema: FeatureSchema) -> str:
        classes = schema.output.get("classes") or []
        if metadata.get("task") == "classification" and classes:
            return classes[-1]
        if metadata.get("task") == "regression":
            return "123.45"
        return "<prediction>"

    @staticmethod
    def _write(path: Path, content: str) -> Path:
        try:
            path.write_text(content, encoding="utf-8")
        except OSError as exc:  # pragma: no cover - disk issues
            raise PackagingError(f"could not write {path}: {exc}") from exc
        return path


def _format_number(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, int | float):
        return f"{value:.4f}".rstrip("0").rstrip(".") if isinstance(value, float) else str(value)
    return str(value)


def _split_description(split_summary: dict[str, Any]) -> str:
    if not split_summary:
        return ""
    return (
        f"{split_summary.get('strategy', '')} - "
        f"train {split_summary.get('n_train', '?')}, "
        f"validation {split_summary.get('n_val', '?')}, "
        f"test {split_summary.get('n_test', '?')}"
    )


__all__ = ["GeneratedInference", "InferenceGenerator"]
