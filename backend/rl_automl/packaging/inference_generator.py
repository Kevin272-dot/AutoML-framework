"""Inference artifact generation (spec §18, §19, §20).

Writes the files that let someone take ``model_package.zip`` to a machine that has never
seen this project:

* ``inference/model_loader.py`` - loads preprocessor, model and schema **in the correct
  order** and exposes ``load_model(path).predict(data)``. It imports nothing from
  ``rl_automl``; that is the whole point of the package.
* ``inference/predict.py`` - a runnable demonstration, also dependency-free.
* ``requirements.txt`` - inference dependencies only, not the training environment.
* ``README.md`` - model, task, expected input schema, install, usage, example I/O, metrics.
* ``inference/example_input.csv`` - a schema-shaped example.

The example input is **synthesised from the schema**, not sampled from the user's data, so
the package never carries user rows out of the system (spec §17).
"""

